// The key structure is fixed by `zhCN`, but leaf values must stay assignable
// across languages. `Localized` maps every string leaf to `string` while
// preserving the nested key shape, so `en-US` is checked for the same keys
// without being forced to equal the Chinese literals.
type Localized<T> = {
  [K in keyof T]: T[K] extends string ? string : Localized<T[K]>;
};

export type Resources = Localized<typeof zhCN>;
